create or replace view public.game_player_list
with (security_invoker = true)
as
select gp.game_id, gp.user_id, p.username, gp.joined_at
from public.game_players gp
join public.profiles p on p.id = gp.user_id
where gp.active;

-- Atomic game creation. The selected Wheel holes are decided server-side once.
create or replace function public.create_game(
  p_bar_ids bigint[],
  p_wheel_count integer default 0,
  p_wheel_mode public.wheel_mode default 'classic',
  p_random_min integer default 1,
  p_random_max integer default 3
)
returns table(game_id bigint, code text)
language plpgsql
security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_game public.games%rowtype;
  v_holes integer := coalesce(array_length(p_bar_ids, 1), 0);
begin
  if v_user is null then raise exception 'Not authenticated'; end if;
  if v_holes < 1 or v_holes > 18 then raise exception 'Choose between 1 and 18 bars'; end if;
  if p_wheel_count < 0 or p_wheel_count > v_holes then raise exception 'Invalid Wheel count'; end if;
  if p_random_min < 1 or p_random_max < p_random_min then raise exception 'Invalid random range'; end if;
  if exists (select 1 from unnest(p_bar_ids) x left join public.bars b on b.id=x where b.id is null) then
    raise exception 'One or more bars do not exist';
  end if;

  insert into public.games(host_id, holes, wheel_count, wheel_mode, random_min, random_max)
  values (v_user, v_holes, p_wheel_count, p_wheel_mode, p_random_min, p_random_max)
  returning * into v_game;

  insert into public.game_players(game_id, user_id) values (v_game.id, v_user);

  with wheel_holes as (
    select n from generate_series(1, v_holes) n order by random() limit p_wheel_count
  )
  insert into public.game_holes(game_id, hole_number, bar_id, wheel_enabled)
  select v_game.id, ordinality::smallint, bar_id,
         exists(select 1 from wheel_holes wh where wh.n = ordinality)
  from unnest(p_bar_ids) with ordinality as selected(bar_id, ordinality);

  return query select v_game.id, v_game.code;
end;
$$;

-- Join by 6-character code.
create or replace function public.join_game(p_code text)
returns bigint
language plpgsql
security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_game_id bigint;
begin
  if v_user is null then raise exception 'Not authenticated'; end if;
  select id into v_game_id from public.games where code = upper(trim(p_code)) and status <> 'finished';
  if v_game_id is null then raise exception 'Game not found'; end if;
  insert into public.game_players(game_id, user_id) values (v_game_id, v_user) on conflict do nothing;
  return v_game_id;
end;
$$;

-- Generates all assignments exactly once for the hole, but only returns the caller's assignment.
create or replace function public.assign_wheel_for_hole(p_game_id bigint, p_hole_number integer)
returns setof public.wheel_assignments
language plpgsql
security definer set search_path = public
as $$
declare
  v_mode public.wheel_mode;
  v_min integer;
  v_max integer;
  v_players integer;
  v_target integer;
  v_challenges integer;
begin
  if not public.is_game_player(p_game_id) then raise exception 'Not a player in this game'; end if;
  if not exists (select 1 from public.game_holes where game_id=p_game_id and hole_number=p_hole_number and wheel_enabled) then
    raise exception 'No Wheel of Doom on this hole';
  end if;

  perform pg_advisory_xact_lock((p_game_id % 2147483647)::integer, p_hole_number);

  if not exists (select 1 from public.wheel_assignments where game_id=p_game_id and hole_number=p_hole_number) then
    select wheel_mode, random_min, random_max into v_mode, v_min, v_max from public.games where id=p_game_id;
    select count(*) into v_players from public.game_players where game_id=p_game_id and active;
    select count(*) into v_challenges from public.wheel_challenges where active;
    if v_players = 0 or v_challenges = 0 then raise exception 'No players or challenges available'; end if;

    if v_mode = 'classic' then
      v_target := 1;
    elsif v_mode = 'everyone' then
      v_target := v_players;
    else
      v_min := least(greatest(v_min, 1), v_players);
      v_max := least(greatest(v_max, v_min), v_players);
      v_target := floor(random() * (v_max - v_min + 1))::integer + v_min;
    end if;

    with selected_players as (
      select user_id, row_number() over () as rn
      from (
        select user_id from public.game_players
        where game_id=p_game_id and active
        order by random()
        limit v_target
      ) p
    ), shuffled_challenges as (
      select id, row_number() over () as rn
      from (
        select id from public.wheel_challenges where active order by random()
      ) c
    )
    insert into public.wheel_assignments(game_id, hole_number, user_id, challenge_id)
    select p_game_id, p_hole_number, sp.user_id, sc.id
    from selected_players sp
    join shuffled_challenges sc on sc.rn = ((sp.rn - 1) % v_challenges) + 1;
  end if;

  return query
  select wa.* from public.wheel_assignments wa
  where wa.game_id=p_game_id and wa.hole_number=p_hole_number and wa.user_id=auth.uid();
end;
$$;

-- The challenge is only returned when the user actually presses Spin.
create or replace function public.reveal_my_wheel_assignment(p_game_id bigint, p_hole_number integer)
returns table(
  assignment_id bigint,
  id bigint,
  emoji text,
  title text,
  description text,
  success_delta smallint,
  fail_delta smallint
)
language plpgsql
security definer set search_path = public
as $$
begin
  perform * from public.assign_wheel_for_hole(p_game_id, p_hole_number);

  update public.wheel_assignments
  set revealed_at = coalesce(revealed_at, now())
  where game_id=p_game_id and hole_number=p_hole_number and user_id=auth.uid();

  return query
  select wa.id, wc.id, wc.emoji, wc.title, wc.description, wc.success_delta, wc.fail_delta
  from public.wheel_assignments wa
  join public.wheel_challenges wc on wc.id=wa.challenge_id
  where wa.game_id=p_game_id and wa.hole_number=p_hole_number and wa.user_id=auth.uid();
end;
$$;

create or replace function public.resolve_my_wheel_assignment(p_game_id bigint, p_hole_number integer, p_completed boolean)
returns smallint
language plpgsql
security definer set search_path = public
as $$
declare
  v_delta smallint;
begin
  if not public.is_game_player(p_game_id) then raise exception 'Not a player in this game'; end if;

  select case when p_completed then wc.success_delta else wc.fail_delta end
  into v_delta
  from public.wheel_assignments wa
  join public.wheel_challenges wc on wc.id=wa.challenge_id
  where wa.game_id=p_game_id and wa.hole_number=p_hole_number and wa.user_id=auth.uid();

  if v_delta is null then raise exception 'No Wheel assignment found'; end if;

  update public.wheel_assignments
  set status = case when p_completed then 'completed'::public.assignment_status else 'failed'::public.assignment_status end,
      score_delta = v_delta,
      resolved_at = now()
  where game_id=p_game_id and hole_number=p_hole_number and user_id=auth.uid();

  return v_delta;
end;
$$;

-- Leave a lobby/game as the current user. If the host leaves a lobby, the lobby is closed.
create or replace function public.leave_game(p_code text)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_game public.games%rowtype;
begin
  if v_user is null then raise exception 'Not authenticated'; end if;
  select * into v_game from public.games where code = upper(trim(p_code));
  if v_game.id is null then return; end if;

  if v_game.host_id = v_user and v_game.status = 'lobby' then
    delete from public.games where id = v_game.id;
  else
    delete from public.game_players where game_id = v_game.id and user_id = v_user;
  end if;
end;
$$;

