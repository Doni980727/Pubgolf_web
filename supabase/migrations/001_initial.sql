create extension if not exists pgcrypto;

create type public.game_status as enum ('lobby', 'active', 'finished');
create type public.wheel_mode as enum ('classic', 'everyone', 'random');
create type public.challenge_duration as enum ('instant', 'whole_pub', 'until_next_pub');
create type public.assignment_status as enum ('assigned', 'completed', 'failed');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 2 and 30),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles(id, username)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), 'player-' || left(new.id::text, 6))
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table public.bars (
  id bigint generated by default as identity primary key,
  name text not null,
  city text not null,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);

create table public.drinks (
  id bigint generated by default as identity primary key,
  bar_id bigint not null references public.bars(id) on delete cascade,
  name text not null,
  size_ml integer,
  price numeric(8,2),
  par smallint not null default 4 check (par between 1 and 20),
  type text
);

create table public.games (
  id bigint generated by default as identity primary key,
  code text not null unique default upper(substr(encode(gen_random_bytes(4), 'hex'), 1, 6)),
  host_id uuid not null references public.profiles(id),
  status public.game_status not null default 'lobby',
  holes smallint not null check (holes between 1 and 18),
  current_hole smallint not null default 1,
  wheel_count smallint not null default 0,
  wheel_mode public.wheel_mode not null default 'classic',
  random_min smallint not null default 1,
  random_max smallint not null default 3,
  created_at timestamptz not null default now(),
  check (wheel_count between 0 and holes),
  check (random_min >= 1 and random_max >= random_min)
);

create table public.game_players (
  game_id bigint not null references public.games(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  active boolean not null default true,
  primary key (game_id, user_id)
);

create table public.game_holes (
  game_id bigint not null references public.games(id) on delete cascade,
  hole_number smallint not null,
  bar_id bigint not null references public.bars(id),
  wheel_enabled boolean not null default false,
  primary key (game_id, hole_number)
);

create table public.results (
  game_id bigint not null references public.games(id) on delete cascade,
  hole_number smallint not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  score smallint not null default 0,
  confirmed boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (game_id, hole_number, user_id)
);

create table public.wheel_challenges (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  emoji text not null,
  title text not null,
  description text not null,
  success_delta smallint not null default 0,
  fail_delta smallint not null default 0,
  duration public.challenge_duration not null default 'whole_pub',
  active boolean not null default true
);

create table public.wheel_assignments (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  hole_number smallint not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  challenge_id bigint not null references public.wheel_challenges(id),
  status public.assignment_status not null default 'assigned',
  score_delta smallint not null default 0,
  assigned_at timestamptz not null default now(),
  revealed_at timestamptz,
  resolved_at timestamptz,
  unique (game_id, hole_number, user_id)
);

