-- Helper functions used by RLS. SECURITY DEFINER avoids recursive game_players policies.
create or replace function public.is_game_player(p_game_id bigint, p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.game_players gp
    where gp.game_id = p_game_id and gp.user_id = p_user_id and gp.active
  );
$$;

create or replace function public.is_game_host(p_game_id bigint, p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.games g where g.id = p_game_id and g.host_id = p_user_id
  );
$$;

